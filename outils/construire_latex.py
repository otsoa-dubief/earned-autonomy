def section(t: str, title: str) -> str:
    i = t.index(title)
    j = t.find("\n## ", i + 1)
    return t[i: j if j > 0 else len(t)]


def demote(md: str, letter: str) -> str:
    md = re.sub(r"^### (\d)", lambda m: f"#### {letter}.{m.group(1)}", md, flags=re.M)
    md = re.sub(r"^## (\d) ", lambda m: f"### {letter}.{m.group(1)} ", md, flags=re.M)
    return md


def body_markdown() -> str:
    return re.sub(r"<!--.*?-->", "", ATELIER.read_text(encoding="utf-8"), flags=re.S)


APPENDIX_OF = {"3": "B", "4": "B", "5": "C", "6": "C"}


def renumber(md: str) -> str:
    """Section numbers of the long version, as they appear inside the appendices: 3-4 are in Appendix B, 5-6 in
    Appendix C, 8 (limitations) is Appendix E; Section 7 is the discussion of the main text."""
    def sub(m):
        num = m.group(1)
        top = num.split(".")[0]
        if top == "8":
            return "Appendix E"
        if top in APPENDIX_OF:
            return f"Section {APPENDIX_OF[top]}.{num}"
        return m.group(0)
    return re.sub(r"\bSection (\d+(?:\.\d+)?)", sub, md)


def appendix_markdown() -> str:
    t = re.sub(r"<!--.*?-->", "", SRC.read_text(encoding="utf-8"), flags=re.S)
    parts = [
        "## A Deviations from the pre-registration\n\n" + section(t, "## Deviations from the preregistration").split("\n", 1)[1],
        "## B Rule and setup in detail\n\n" + demote(section(t, "## 3 The earned-autonomy rule"), "B")
        + "\n" + demote(section(t, "## 4 Experimental setup"), "B"),
        "## C Pre-registered analysis and results in detail\n\n" + demote(section(t, "## 5 Preregistered analysis"), "C")
        + "\n" + demote(section(t, "## 6 Results"), "C"),
        "## E Limitations in full\n\n" + section(t, "## 8 Limitations").split("\n", 1)[1],
        REPRO,
    ]
    parts = [renumber(x) for x in parts[:4]] + parts[4:]
    return "\n\n".join(parts[:3]), "\n\n".join(parts[3:])


def acknowledgements() -> str:
    t = SRC.read_text(encoding="utf-8")
    return renumber(section(t, "## Acknowledgements and declarations"))


def abstract() -> str:
    t = SRC.read_text(encoding="utf-8")
    s = t.index("## Abstract") + len("## Abstract")
    return t[s:].strip().split("\n\n")[0]


def pandoc(md: str) -> str:
    r = subprocess.run(["pandoc", "-f", "markdown-implicit_figures+implicit_figures", "-t", "latex",
                        "--wrap=preserve", "--top-level-division=section"],
                       input=md, capture_output=True, text=True, check=True)
    return breakable(r.stdout.replace("ρ̂", r"\ensuremath{\hat{\rho}}"))


def breakable(tex: str) -> str:
    """Lets long URLs and file paths break at the end of a line (they overflowed the margin otherwise)."""
    def url(m):
        return m.group(1) + r"\url{" + m.group(2).replace(r"\_", "_") + "}" + m.group(3)
    tex = re.sub(r"(^|[^{\w])(https?://[^\s{}]+?)([.,;:)]*)(?=[\s}]|$)", url, tex, flags=re.M)

    def tt(m):
        s = re.sub(r"(/|\\_|\.)(?=.)", lambda k: k.group(1) + r"\allowbreak{}", m.group(1))
        return r"\texttt{" + s + "}"
    return re.sub(r"\\texttt\{([^{}]*)\}", tt, tex)


def bib() -> str:
    t = SRC.read_text(encoding="utf-8")
    refs = [l[2:] for l in t[t.index("## References"):].split("\n") if l.startswith("- ")]
    out, seen = [], set()
    for ref in refs:
        m = re.match(r"([^\s,(.]+)[^(]*\((\d{4}[a-z]?)\)", ref)
        key = (re.sub(r"\W", "", m.group(1)).lower() + m.group(2)) if m else re.sub(r"\W", "", ref[:12]).lower()
        while key in seen:
            key += "x"
        seen.add(key)
        note = pandoc(ref).strip()
        out.append(f"@misc{{{key},\n  note = {{{note}}}\n}}\n")
    return "\n".join(out)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, str(ROOT / "outils" / "tables_latex.py"), str(ROOT / "article" / "resultats"),
                    str(OUT / "tables")], check=True, capture_output=True)
    (OUT / "body.tex").write_text(pandoc(body_markdown() + "\n\n" + acknowledgements()), encoding="utf-8")
    abc, ef = appendix_markdown()
    (OUT / "appendix_abc.tex").write_text(pandoc(abc), encoding="utf-8")
    (OUT / "appendix_ef.tex").write_text(pandoc(ef), encoding="utf-8")
    (OUT / "abstract.tex").write_text(pandoc(abstract()), encoding="utf-8")
    (OUT / "refs.bib").write_text(bib(), encoding="utf-8")
    print("body.tex, abstract.tex, refs.bib, tables/ ->", OUT)


if __name__ == "__main__":
    main()
